def random_datetime(month_start, with_time=True):
    days = pd.date_range(month_start, month_start + pd.offsets.MonthEnd(1), freq="D")
    w = WD_W[days.dayofweek]; d = days[rng.choice(len(days), p=w / w.sum())]
    if not with_time:
        return d
    h = rng.choice(24, p=HOUR_W / HOUR_W.sum())
    return d + pd.Timedelta(hours=int(h), minutes=int(rng.integers(60)))

