def dirty(df, date_col, cat_col, variants, with_time):
    df = df.sort_values(date_col).reset_index(drop=True)
    fmt_main = "%Y-%m-%d %H:%M:%S" if with_time else "%Y-%m-%d"
    fmt_alt = "%d.%m.%Y %H:%M" if with_time else "%d.%m.%Y"
    alt = rng.random(len(df)) < 0.01
    df[date_col] = [d.strftime(fmt_alt if a else fmt_main) for d, a in zip(df[date_col], alt)]
    for i in np.where(rng.random(len(df)) < 0.015)[0]:     # разное написание категорий
        v = variants.get(df.at[i, cat_col])
        if v: df.at[i, cat_col] = pick(v)
    sp = rng.random(len(df)) < 0.01                        # лишние пробелы
    df.loc[sp, "org_id"] = df.loc[sp, "org_id"] + " "
    dup = df.sample(frac=0.012, random_state=SEED)          # двойная регистрация
    dup_new = dup.copy(); dup_new["id"] = [new_id() for _ in range(len(dup_new))]
    exact = df.sample(n=max(3, len(df) // 400), random_state=SEED + 2)
    return pd.concat([df, dup_new, exact]).sample(frac=1, random_state=SEED).reset_index(drop=True)

